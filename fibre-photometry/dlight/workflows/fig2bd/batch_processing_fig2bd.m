%% BATCH_PROCESSING_FIG2BD
% Process habituation and VG/RG/RV recordings used for Fig. 2b-d.

clear; clc;

sensor_root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(sensor_root);
addpath(fullfile(sensor_root,'config'));
addpath(fullfile(sensor_root,'functions'));
paths = dlight_paths('fig2bd');

subjects = fig2bd_subjects();
conditions = fig2bd_conditions();
process_only_animals = subjects;
process_only_conditions = conditions;

%% Habituation recordings
for i = 1:numel(subjects)
    animal = subjects{i};
    if ~isempty(process_only_animals) && ...
            ~any(strcmp(process_only_animals,animal))
        continue;
    end

    cfg = fig2bd_config(animal,'hab3');
    data_folder = fullfile(paths.data_root,'hab3',animal);
    fprintf('\n=== Fig. 2b-d | hab3 | %s ===\n',animal);

    if ~valid_recording_folder(data_folder)
        fprintf(2,'[ERROR] Incomplete recording folder: %s\n',data_folder);
        continue;
    end

    try
        process_fig2bd_dlight( ...
            'mode','hab3', ...
            'condition','hab3', ...
            'data_folder',data_folder, ...
            'subject',animal, ...
            'output_root',paths.fig2bd_output_root, ...
            'signal_stream',cfg.signal_stream, ...
            'reference_stream',cfg.reference_stream, ...
            'raw_start_s',cfg.raw_start_s, ...
            'lowpass_hz',cfg.hab3.lowpass_hz, ...
            'target_fs',cfg.target_fs, ...
            'bleach_smoothing_window',cfg.hab3.bleach_smoothing_window, ...
            'hab3_fit_trim_start',cfg.hab3.fit_trim_start, ...
            'hab3_fit_trim_end',cfg.hab3.fit_trim_end, ...
            'start_point_405',cfg.hab3.start_point_405, ...
            'start_point_465',cfg.hab3.start_point_465, ...
            'timestamps',cfg.hab3.timestamps, ...
            'fpx_time_range',cfg.test.fpx_time_range);
    catch ME
        report_error('hab3',animal,ME);
    end
end

%% VG, RG and RV recordings
for c = 1:numel(conditions)
    condition = conditions{c};
    if strcmpi(condition,'hab3') || ...
            (~isempty(process_only_conditions) && ...
            ~any(strcmp(process_only_conditions,condition)))
        continue;
    end

    for i = 1:numel(subjects)
        animal = subjects{i};
        if ~isempty(process_only_animals) && ...
                ~any(strcmp(process_only_animals,animal))
            continue;
        end

        cfg = fig2bd_config(animal,condition);
        data_folder = fullfile(paths.data_root,lower(condition),animal);
        hab3_file = fullfile(paths.fig2bd_output_root,'hab3',animal, ...
            ['hab3_' animal '_processed.mat']);
        fprintf('\n=== Fig. 2b-d | %s | %s ===\n',condition,animal);

        if ~valid_recording_folder(data_folder) || ~isfile(hab3_file)
            fprintf(2,'[ERROR] Missing recording files or hab3 output.\n');
            continue;
        end

        try
            process_fig2bd_dlight( ...
                'mode','test', ...
                'condition',condition, ...
                'data_folder',data_folder, ...
                'subject',animal, ...
                'hab3_fit_file',hab3_file, ...
                'output_root',paths.fig2bd_output_root, ...
                'signal_stream',cfg.signal_stream, ...
                'reference_stream',cfg.reference_stream, ...
                'raw_start_s',cfg.raw_start_s, ...
                'lowpass_hz',cfg.test.lowpass_hz, ...
                'target_fs',cfg.test.target_fs, ...
                'baseline_smoothing_window',cfg.test.baseline_fit_smoothing_window, ...
                'use_bleach_correction',cfg.test.use_bleach_correction, ...
                'timestamps',cfg.test.timestamps, ...
                'fpx_time_range',cfg.test.fpx_time_range);
        catch ME
            report_error(condition,animal,ME);
        end
    end
end

fprintf('\nFig. 2b-d preprocessing complete.\n');

function tf = valid_recording_folder(folder)
if ~isfolder(folder)
    tf = false;
    return;
end
[~,subject] = fileparts(folder);
prefix = ['sub-' subject '_'];
tf = isfile(fullfile(folder,[prefix 'photometry.parquet'])) && ...
    isfile(fullfile(folder,[prefix 'notes.csv'])) && ...
    isfile(fullfile(folder,[prefix 'metadata.json']));
end

function report_error(condition,animal,ME)
fprintf(2,'[ERROR] %s | %s: %s\n',condition,animal,ME.message);
for k = 1:numel(ME.stack)
    fprintf(2,'  %s (line %d)\n',ME.stack(k).name,ME.stack(k).line);
end
end
