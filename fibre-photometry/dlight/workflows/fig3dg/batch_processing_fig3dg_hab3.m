%% BATCH_PROCESSING_FIG3DG_HAB3
clear; clc;

sensor_root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(sensor_root);
addpath(fullfile(sensor_root,'config'));
addpath(fullfile(sensor_root,'functions'));
paths = dlight_paths('fig3dg');

subjects = fig3dg_subjects();
process_only = subjects;  % e.g. {'032417'} for a validation run

for i = 1:numel(subjects)
    animal = subjects{i};
    if ~isempty(process_only) && ~any(strcmp(process_only,animal)), continue; end

    cfg = fig3dg_config(animal);
    data_folder = fullfile(paths.data_root,'hab3',animal);

    fprintf('\n=== Fig. 3d-g | hab3 | %s ===\n',animal);
    fprintf('Data folder: %s\n',data_folder);

    if ~valid_recording_folder(data_folder)
        fprintf(2,'[ERROR] %s: recording files not found.\n',animal);
        continue;
    end

    try
        process_fig3dg_hab3_dlight( ...
            'day','hab3', ...
            'data_folder',data_folder, ...
            'subject',animal, ...
            'timestamps',cfg.hab3.timestamps, ...
            'output_root',paths.output_root, ...
            'raw_start_s',cfg.raw_start_s, ...
            'lowpass_hz',cfg.lowpass_hz, ...
            'target_fs',cfg.target_fs, ...
            'bleach_smoothing_method',cfg.hab3.bleach_smoothing_method, ...
            'bleach_smoothing_window',cfg.hab3.bleach_smoothing_window, ...
            'bleach_fit_start_idx',cfg.hab3.bleach_fit_start_idx, ...
            'bleach_fit_end_trim_idx',cfg.hab3.bleach_fit_end_trim_idx, ...
            'start_point_405',cfg.hab3.start_point_405, ...
            'start_point_465',cfg.hab3.start_point_465, ...
            'baseline_fit_smoothing_method',cfg.hab3.baseline_fit_smoothing_method, ...
            'baseline_fit_smoothing_window',cfg.hab3.baseline_fit_smoothing_window, ...
            'baseline_fit_start_offset',cfg.hab3.baseline_fit_start_offset, ...
            'save_mat',true, ...
            'save_figures',false);
        fprintf('[OK] %s complete.\n',animal);
    catch ME
        fprintf(2,'[ERROR] %s: %s\n',animal,ME.message);
    end
end

fprintf('\nFig. 3d-g hab3 batch complete.\n');

function tf = valid_recording_folder(folder)
if ~isfolder(folder)
    tf = false;
    return;
end
[~,subject] = fileparts(folder);
prefix = ['sub-' subject '_'];
tf = isfile(fullfile(folder,[prefix 'photometry.parquet'])) && ...
    isfile(fullfile(folder,[prefix 'notes.csv'])) && ...
    isfile(fullfile(folder,[prefix 'metadata.json']));
end
